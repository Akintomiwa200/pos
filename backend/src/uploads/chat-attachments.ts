import { BadRequestException } from "@nestjs/common";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import type { ChatAttachment } from "../chat/chat.types";

/** Chat attachments are kept outside the public web root and served by ChatController. */
export const MAX_CHAT_ATTACHMENT_BYTES = 20 * 1024 * 1024;
export const MAX_CHAT_ATTACHMENTS_PER_MESSAGE = 10;
export const CHAT_ATTACHMENT_TYPES_LABEL =
  "PNG, JPEG, GIF, WebP, PDF, CSV, TSV, JSON, TXT, DOC, DOCX, XLS, XLSX and ZIP files only (max 20 MB).";

export const CHAT_UPLOAD_DIR = join(process.cwd(), "data", "chat-uploads");
export const CHAT_UPLOAD_METADATA_FILE = join(process.cwd(), "data", "chat-uploads.json");

/** Canonical MIME types keyed by the only extensions we accept. */
const ALLOWED_TYPES: Record<string, string> = {
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  gif: "image/gif",
  webp: "image/webp",
  pdf: "application/pdf",
  csv: "text/csv",
  tsv: "text/tab-separated-values",
  json: "application/json",
  txt: "text/plain",
  doc: "application/msword",
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  xls: "application/vnd.ms-excel",
  xlsx: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  zip: "application/zip",
};

/** The public shape stored on messages and sent over SSE. No filesystem paths. */
export type ChatAttachmentRecord = ChatAttachment & {
  /** Random name generated by the server; original names are display-only. */
  storedName: string;
  uploaderId: string;
  conversationId?: string;
  messageId?: string;
  status: "pending" | "attached" | "orphan";
  createdAt: string;
  orphanedAt?: string;
};

export type ValidatedChatAttachment = {
  name: string;
  mimeType: string;
  extension: string;
  size: number;
};

function safeDisplayName(originalName?: string): string {
  const lastPart = String(originalName ?? "")
    .replace(/\\/g, "/")
    .split("/")
    .pop()
    ?.replace(/[\u0000-\u001f\u007f]/g, "")
    .trim();
  return (lastPart || "attachment").slice(0, 120);
}

/** Extension allowlist is the security boundary; MIME is derived server-side. */
export function validateChatAttachment(file?: Express.Multer.File): ValidatedChatAttachment {
  if (!file?.buffer?.length) {
    throw new BadRequestException("Choose a file to upload.");
  }
  const size = file.size || file.buffer.length;
  if (size > MAX_CHAT_ATTACHMENT_BYTES) {
    throw new BadRequestException(`Files must be 20 MB or smaller. ${CHAT_ATTACHMENT_TYPES_LABEL}`);
  }
  const name = safeDisplayName(file.originalname);
  const ext = name.includes(".") ? name.split(".").pop()!.toLowerCase() : "";
  const mimeType = ALLOWED_TYPES[ext];
  if (!mimeType) {
    throw new BadRequestException(`Unsupported file type "${ext || "unknown"}". ${CHAT_ATTACHMENT_TYPES_LABEL}`);
  }
  return { name, mimeType, extension: `.${ext}`, size };
}

export function publicChatAttachment(record: ChatAttachmentRecord): ChatAttachment {
  return {
    id: record.id,
    name: record.name,
    mimeType: record.mimeType,
    size: record.size,
    url: `/api/chat/files/${encodeURIComponent(record.id)}`,
  };
}

/** Never let metadata (which is user-influenced) escape the upload directory. */
function safeStoredName(storedName: string): boolean {
  return /^[0-9a-f-]{36}\.[a-z0-9]{1,5}$/.test(storedName);
}

export async function storeChatAttachmentFile(
  file: Express.Multer.File,
  extension: string,
): Promise<string> {
  await mkdir(CHAT_UPLOAD_DIR, { recursive: true });
  const storedName = `${randomUUID()}${extension}`;
  await writeFile(join(CHAT_UPLOAD_DIR, storedName), file.buffer);
  return storedName;
}

export async function readChatAttachmentFile(storedName: string): Promise<Buffer | null> {
  if (!safeStoredName(storedName)) return null;
  try {
    return await readFile(join(CHAT_UPLOAD_DIR, storedName));
  } catch {
    return null;
  }
}

export async function removeChatAttachmentFile(storedName: string): Promise<void> {
  if (!safeStoredName(storedName)) return;
  await rm(join(CHAT_UPLOAD_DIR, storedName), { force: true });
}

export async function readChatAttachmentRecords(): Promise<ChatAttachmentRecord[]> {
  try {
    const raw = await readFile(CHAT_UPLOAD_METADATA_FILE, "utf8");
    const parsed: unknown = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter(
      (row): row is ChatAttachmentRecord =>
        Boolean(row && typeof row.id === "string" && typeof row.storedName === "string"),
    );
  } catch {
    return [];
  }
}

export async function writeChatAttachmentRecords(records: ChatAttachmentRecord[]): Promise<void> {
  await mkdir(dirname(CHAT_UPLOAD_METADATA_FILE), { recursive: true });
  const temporary = `${CHAT_UPLOAD_METADATA_FILE}.${randomUUID()}.tmp`;
  await writeFile(temporary, JSON.stringify(records, null, 2), "utf8");
  await rename(temporary, CHAT_UPLOAD_METADATA_FILE);
}

export function contentDisposition(name: string, inline: boolean): string {
  const ascii = name.replace(/[\r\n"\\]/g, "_");
  const kind = inline ? "inline" : "attachment";
  return `${kind}; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(name)}`;
}
